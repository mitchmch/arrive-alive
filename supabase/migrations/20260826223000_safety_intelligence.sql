-- The Edge Function validates the actor and computes the deterministic payload.
-- This RPC provides one atomic, idempotent write boundary at journey completion.
create or replace function public.finalize_journey_safety(
  p_actor_user_id bigint,
  p_journey_id bigint,
  p_journey_update jsonb,
  p_samples jsonb,
  p_episodes jsonb,
  p_assessment jsonb
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  owned public.journeys;
  assessment_row public.journey_safety_assessments;
  item jsonb;
begin
  select * into owned from public.journeys
    where id = p_journey_id and user_id = p_actor_user_id and deleted_at is null
    for update;
  if owned.id is null then raise exception 'journey not found'; end if;

  update public.journeys set
    status = 'completed',
    end_time = coalesce((p_journey_update->>'endTime')::timestamptz, now()),
    max_speed = coalesce((p_journey_update->>'maxSpeed')::double precision, 0),
    avg_speed = coalesce((p_journey_update->>'averageSpeed')::double precision, 0),
    distance = coalesce((p_journey_update->>'distance')::double precision, 0),
    violation_count = jsonb_array_length(p_episodes),
    score = greatest(0, 100 - (jsonb_array_length(p_episodes) * 15))
  where id = p_journey_id;

  for item in select value from jsonb_array_elements(p_samples)
  loop
    insert into public.speed_samples(
      stable_id, journey_id, user_id, client_sample_id, sequence_number, recorded_at, speed,
      speed_limit, accuracy, is_moving, latitude, longitude, accepted, rejection_reason
    ) values (
      item->>'id', p_journey_id, p_actor_user_id, (item->>'id')::uuid,
      (item->>'sequence')::integer, (item->>'recordedAt')::timestamptz,
      (item->>'speedKph')::numeric, (item->>'speedLimitKph')::numeric,
      nullif(item->>'accuracyM','')::numeric,
      coalesce((item->>'speedKph')::numeric >= 3, false),
      nullif(item->>'latitude','')::double precision,
      nullif(item->>'longitude','')::double precision,
      coalesce((item->>'accepted')::boolean, true), item->>'rejectionReason'
    ) on conflict (stable_id) do nothing;
  end loop;

  for item in select value from jsonb_array_elements(p_episodes)
  loop
    insert into public.violation_episodes(
      id, journey_id, agency_id, started_at, ended_at, sample_count,
      peak_speed_kph, average_speed_kph, duration_seconds, speed_limit_kph, over_by_kph
    ) values (
      (item->>'id')::uuid, p_journey_id, owned.agency_id,
      (item->>'startedAt')::timestamptz, (item->>'endedAt')::timestamptz,
      (item->>'sampleCount')::integer, (item->>'peakSpeedKph')::numeric,
      (item->>'averageSpeedKph')::numeric, (item->>'durationSeconds')::integer,
      (item->>'speedLimitKph')::numeric, (item->>'overByKph')::numeric
    ) on conflict (id) do nothing;
  end loop;

  insert into public.journey_safety_assessments(
    journey_id, agency_id, status, result_type, speed_limit_kph,
    accepted_sample_count, rejected_sample_count, episode_count,
    peak_speed_kph, average_speed_kph, duration_seconds, max_over_by_kph,
    confidence, reasons, deterministic_summary
  ) values (
    p_journey_id, owned.agency_id, (p_assessment->>'status')::public.safety_status,
    (p_assessment->>'resultType')::public.board_result_type,
    (p_assessment->>'speedLimitKph')::numeric,
    (p_assessment->>'acceptedSampleCount')::integer,
    (p_assessment->>'rejectedSampleCount')::integer,
    (p_assessment->>'episodeCount')::integer,
    (p_assessment->>'peakSpeedKph')::numeric,
    (p_assessment->>'averageSpeedKph')::numeric,
    (p_assessment->>'durationSeconds')::integer,
    (p_assessment->>'maxOverByKph')::numeric,
    (p_assessment->>'confidence')::numeric, p_assessment->'reasons',
    p_assessment->>'deterministicSummary'
  )
  on conflict (journey_id) do update set
    status=excluded.status, result_type=excluded.result_type,
    accepted_sample_count=excluded.accepted_sample_count,
    rejected_sample_count=excluded.rejected_sample_count,
    episode_count=excluded.episode_count, peak_speed_kph=excluded.peak_speed_kph,
    average_speed_kph=excluded.average_speed_kph, duration_seconds=excluded.duration_seconds,
    max_over_by_kph=excluded.max_over_by_kph, confidence=excluded.confidence,
    reasons=excluded.reasons, deterministic_summary=excluded.deterministic_summary
  returning * into assessment_row;

  insert into public.speed_board_entries(
    journey_id, assessment_id, agency_id, result_type, evidence, summary
  ) values (
    p_journey_id, assessment_row.id, owned.agency_id, assessment_row.result_type,
    jsonb_build_object(
      'sampleCount', assessment_row.accepted_sample_count,
      'episodeCount', assessment_row.episode_count,
      'peakSpeedKph', assessment_row.peak_speed_kph,
      'averageSpeedKph', assessment_row.average_speed_kph,
      'durationSeconds', assessment_row.duration_seconds,
      'speedLimitKph', assessment_row.speed_limit_kph,
      'maxOverByKph', assessment_row.max_over_by_kph,
      'confidence', assessment_row.confidence,
      'reasons', assessment_row.reasons
    ),
    assessment_row.deterministic_summary
  ) on conflict (journey_id) do update set
    assessment_id=excluded.assessment_id, result_type=excluded.result_type,
    evidence=excluded.evidence, summary=excluded.summary, published_at=now(), active=true;

  insert into public.audit_log(actor_user_id, action, entity_type, entity_id, details)
  values (p_actor_user_id, 'finalize_safety', 'journey', p_journey_id::text,
    jsonb_build_object('assessmentId', assessment_row.id, 'rulesVersion', assessment_row.rules_version));

  return to_jsonb(assessment_row);
end $$;

revoke all on function public.finalize_journey_safety(bigint,bigint,jsonb,jsonb,jsonb,jsonb)
  from public, anon, authenticated;

