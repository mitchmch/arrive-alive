-- Evidence-based safety intelligence. Decisions are made by deterministic SQL
-- and TypeScript rules. AI-authored text is stored separately and is never an
-- input to assessment or rollup status.
create type public.safety_status as enum ('trusted', 'avoid', 'insufficient_evidence');
create type public.board_result_type as enum ('violator', 'within_limit');
create type public.rollup_period as enum ('daily', 'weekly', 'monthly');

-- Compatibility boundary with 20260826222000_speed_safety_evidence.sql.
-- That migration may already create this Flutter ingestion table in an
-- existing review branch. IF NOT EXISTS keeps this migration safe in either
-- ordering while making a fresh migration chain self-contained.
create table if not exists public.speed_samples (
  id bigint generated by default as identity primary key,
  stable_id text not null unique,
  journey_id bigint not null references public.journeys(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  recorded_at timestamptz not null,
  speed numeric(7,2) not null check (speed between 0 and 300),
  speed_limit numeric(7,2) not null check (speed_limit between 1 and 300),
  latitude double precision,
  longitude double precision,
  accuracy numeric(7,2),
  is_moving boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.speed_samples
