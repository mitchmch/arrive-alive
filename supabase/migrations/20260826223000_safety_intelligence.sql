create table public.violation_episodes (
  id uuid primary key,
  journey_id bigint not null references public.journeys(id) on delete cascade,
  agency_id bigint references public.agencies(id) on delete set null,
  started_at timestamptz not null,
  ended_at timestamptz not null,
  sample_count integer not null check (sample_count > 0),
  peak_speed_kph numeric(7,2) not null,
  average_speed_kph numeric(7,2) not null,
  duration_seconds integer not null check (duration_seconds >= 0),
  speed_limit_kph numeric(7,2) not null,
  over_by_kph numeric(7,2) not null check (over_by_kph > 0),
  created_at timestamptz not null default now(),
  check (ended_at >= started_at),
  unique (journey_id, started_at)
);

create table public.speed_reports (
  id uuid primary key default gen_random_uuid(),
  stable_id uuid not null unique,
  reporter_user_id bigint not null references public.users(id) on delete cascade,
  agency_id bigint not null references public.agencies(id) on delete cascade,
  journey_id bigint references public.journeys(id) on delete set null,
